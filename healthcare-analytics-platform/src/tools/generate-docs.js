// Writes the reference pages that come straight from the code, so they cannot drift from it:
// KPI definitions, data quality rules and data lineage.
//   npm run docs:generate
const fs = require('fs');
const path = require('path');
const { KPIS } = require('../server/kpis');
const { PRE_LOAD_RULES, POST_LOAD_RULES } = require('../pipeline/quality');
const { LINEAGE } = require('./lineage');

const DOCS = path.join(__dirname, '..', '..', 'docs');
const esc = s => String(s).replace(/\|/g, '\\|').replace(/\n\s*/g, ' ');
const NOTE = '<!-- Generated by npm run docs:generate from the source code. Edit the code, not this file. -->\n\n';

function kpis() {
  return `${NOTE}# KPI definitions\n\nEvery figure on the dashboard comes from one of these definitions. ` +
    'The SQL runs against `analytics_marts.appointments` (alias `a`) with the dashboard filters added as parameters.\n\n' +
    KPIS.map(k => `## ${k.name}\n\n${k.definition}\n\n\`\`\`sql\n${k.sql.trim()}\n\`\`\`\n`).join('\n');
}

function rules() {
  const row = r => `| \`${r.name}\` | ${r.dataset} | ${r.severity} | ${r.action} | ${esc(r.description)} |`;
  return `${NOTE}# Data quality rules\n\nRules run on every pipeline run and their results are stored in ` +
    '`analytics_meta.dq_results`.\n\n' +
    '* **quarantine**: failing rows are kept out of the warehouse and copied (pseudonymised) to `analytics_meta.quarantine`.\n' +
    '* **flag**: rows are loaded; the failure is recorded for review.\n' +
    '* **report**: a check on the result of the load (reconciliation and consistency).\n' +
    '* **block**: the run stops before loading (used for unexpected source schema changes).\n\n' +
    '## Before loading\n\n| Rule | Dataset | Severity | Action | What it checks |\n|---|---|---|---|---|\n' +
    PRE_LOAD_RULES.map(row).join('\n') +
    '\n| `data_freshness` | pipeline | warning | report | The previous successful run finished within PIPELINE_FRESHNESS_HOURS. |' +
    '\n| `unexpected_schema_change` | source_schema | error | block | Columns the pipeline reads still exist with the same type as when it first ran. |' +
    '\n\n## After loading\n\n| Rule | Dataset | Severity | Action | What it checks |\n|---|---|---|---|---|\n' +
    POST_LOAD_RULES.map(row).join('\n') + '\n';
}

function lineage() {
  return `${NOTE}# Data lineage\n\nAlso stored in \`analytics_meta.lineage\` and shown on the dashboard's Data quality page.\n\n` +
    '| Analytics object | Comes from | How |\n|---|---|---|\n' +
    LINEAGE.map(([t, s, h]) => `| \`${t}\` | \`${s}\` | ${esc(h)} |`).join('\n') + '\n';
}

if (require.main === module) {
  fs.mkdirSync(DOCS, { recursive: true });
  fs.writeFileSync(path.join(DOCS, 'kpi-definitions.md'), kpis());
  fs.writeFileSync(path.join(DOCS, 'data-quality-rules.md'), rules());
  fs.writeFileSync(path.join(DOCS, 'data-lineage.md'), lineage());
  console.log('Wrote docs/kpi-definitions.md, docs/data-quality-rules.md and docs/data-lineage.md');
}
