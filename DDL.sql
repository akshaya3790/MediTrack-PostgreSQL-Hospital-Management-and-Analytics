-- PostgreSQL schema. Run with: psql -U postgres -f DDL.sql
DROP DATABASE IF EXISTS hms;
CREATE DATABASE hms;
\c hms

CREATE TABLE Patient(
email VARCHAR(100) PRIMARY KEY,
password VARCHAR(100) NOT NULL, -- bcrypt hash
name VARCHAR(100) NOT NULL,
address VARCHAR(200) NOT NULL,
gender VARCHAR(20) NOT NULL,
phone VARCHAR(20),
dob DATE
);

CREATE TABLE MedicalHistory(
id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
date DATE NOT NULL,
conditions VARCHAR(255) NOT NULL,
surgeries VARCHAR(255) NOT NULL,
medication VARCHAR(255) NOT NULL
);

CREATE TABLE Doctor(
email VARCHAR(100) PRIMARY KEY,
gender VARCHAR(20) NOT NULL,
password VARCHAR(100) NOT NULL, -- bcrypt hash
name VARCHAR(100) NOT NULL,
specialization VARCHAR(50) NOT NULL DEFAULT 'General Medicine'
);

-- Each appointment records the doctor it is booked with
CREATE TABLE Appointment(
id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
doctor VARCHAR(100) NOT NULL,
date DATE NOT NULL,
starttime TIME NOT NULL,
endtime TIME NOT NULL,
status VARCHAR(10) NOT NULL DEFAULT 'NotDone' CHECK (status IN ('NotDone', 'Done')),
FOREIGN KEY (doctor) REFERENCES Doctor (email) ON DELETE CASCADE ON UPDATE CASCADE,
CHECK (starttime < endtime),
-- a doctor cannot have two appointments starting at the same time
UNIQUE (doctor, date, starttime)
);

CREATE TABLE PatientsAttendAppointments(
patient VARCHAR(100) NOT NULL,
appt INT NOT NULL,
concerns VARCHAR(255) NOT NULL,
symptoms VARCHAR(255) NOT NULL,
FOREIGN KEY (patient) REFERENCES Patient (email) ON DELETE CASCADE ON UPDATE CASCADE,
FOREIGN KEY (appt) REFERENCES Appointment (id) ON DELETE CASCADE,
PRIMARY KEY (patient, appt)
);

-- A schedule is a set of working hours; the days it applies to are in ScheduleDays
CREATE TABLE Schedule(
id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
starttime TIME NOT NULL,
endtime TIME NOT NULL,
breaktime TIME NOT NULL,
CHECK (starttime < endtime)
);

CREATE TABLE ScheduleDays(
sched INT NOT NULL,
day VARCHAR(10) NOT NULL CHECK (day IN ('Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday')),
FOREIGN KEY (sched) REFERENCES Schedule (id) ON DELETE CASCADE,
PRIMARY KEY (sched, day)
);

CREATE TABLE PatientsFillHistory(
patient VARCHAR(100) NOT NULL,
history INT NOT NULL,
FOREIGN KEY (patient) REFERENCES Patient (email) ON DELETE CASCADE ON UPDATE CASCADE,
FOREIGN KEY (history) REFERENCES MedicalHistory (id) ON DELETE CASCADE,
PRIMARY KEY (history)
);

-- A row exists only once the doctor has actually diagnosed the appointment
CREATE TABLE Diagnose(
appt INT NOT NULL,
doctor VARCHAR(100) NOT NULL,
diagnosis VARCHAR(255) NOT NULL,
prescription VARCHAR(255) NOT NULL,
FOREIGN KEY (appt) REFERENCES Appointment (id) ON DELETE CASCADE,
FOREIGN KEY (doctor) REFERENCES Doctor (email) ON DELETE CASCADE ON UPDATE CASCADE,
PRIMARY KEY (appt, doctor)
);

CREATE TABLE DocsHaveSchedules(
sched INT NOT NULL,
doctor VARCHAR(100) NOT NULL,
FOREIGN KEY (sched) REFERENCES Schedule (id) ON DELETE CASCADE,
FOREIGN KEY (doctor) REFERENCES Doctor (email) ON DELETE CASCADE ON UPDATE CASCADE,
PRIMARY KEY (sched, doctor)
);

CREATE TABLE DoctorViewsHistory(
history INT NOT NULL,
doctor VARCHAR(100) NOT NULL,
FOREIGN KEY (doctor) REFERENCES Doctor (email) ON DELETE CASCADE ON UPDATE CASCADE,
FOREIGN KEY (history) REFERENCES MedicalHistory (id) ON DELETE CASCADE,
PRIMARY KEY (history, doctor)
);

