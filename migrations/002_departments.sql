-- ---------- Doctors belong to a department ----------
-- The fixed list check is replaced by a link to the Department table, so new departments
-- added by an administrator can have doctors, and renaming a department updates its doctors.

ALTER TABLE Doctor DROP CONSTRAINT IF EXISTS doctor_specialization_valid;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'doctor_department_fk') THEN
    -- Any doctor whose department is not in the table moves to General Medicine first
    UPDATE Doctor SET specialization = 'General Medicine'
      WHERE specialization NOT IN (SELECT name FROM Department);
    ALTER TABLE Doctor ADD CONSTRAINT doctor_department_fk
      FOREIGN KEY (specialization) REFERENCES Department (name) ON UPDATE CASCADE;
  END IF;
END $$;
CREATE INDEX IF NOT EXISTS doctor_specialization_idx ON Doctor (specialization);

-- A doctor cannot have two appointments starting at the same time. The original schema
-- already has this rule; it is added here only for databases created without it.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint c JOIN pg_class t ON t.oid = c.conrelid
    WHERE t.relname = 'appointment' AND c.contype = 'u'
      AND (SELECT ARRAY_AGG(a.attname::text ORDER BY a.attname) FROM pg_attribute a
           WHERE a.attrelid = t.oid AND a.attnum = ANY (c.conkey)) = ARRAY['date', 'doctor', 'starttime']
  ) AND NOT EXISTS (
    SELECT 1 FROM Appointment GROUP BY doctor, date, starttime HAVING COUNT(*) > 1
  ) THEN
    ALTER TABLE Appointment ADD CONSTRAINT appointment_doctor_slot_unique UNIQUE (doctor, date, starttime);
  END IF;
END $$;

