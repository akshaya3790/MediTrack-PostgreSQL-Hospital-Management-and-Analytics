-- ---------- Departments ----------

CREATE TABLE IF NOT EXISTS Department (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(50) NOT NULL UNIQUE,
  slug VARCHAR(60) NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  short_description VARCHAR(160) NOT NULL CHECK (BTRIM(short_description) <> ''),
  description TEXT NOT NULL CHECK (CHAR_LENGTH(BTRIM(description)) BETWEEN 1 AND 2000),
  -- Kinds of problems the department usually sees, one per array item
  common_concerns TEXT[] NOT NULL DEFAULT '{}',
  icon VARCHAR(30) NOT NULL DEFAULT 'activity',
  image_url VARCHAR(300) CHECK (image_url IS NULL OR image_url ~ '^https://'),
  -- Contact and opening details are left empty until the hospital publishes them
  phone VARCHAR(20) CHECK (phone IS NULL OR phone ~ '^\+?[0-9][0-9 ()-]{5,18}$'),
  email VARCHAR(100) CHECK (email IS NULL OR email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'),
  location VARCHAR(120),
  operating_hours VARCHAR(200),
  instructions VARCHAR(500),
  sort_order INT NOT NULL DEFAULT 0,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS DepartmentService (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department_id INT NOT NULL REFERENCES Department (id) ON DELETE CASCADE,
  name VARCHAR(100) NOT NULL CHECK (BTRIM(name) <> ''),
  description VARCHAR(300),
  sort_order INT NOT NULL DEFAULT 0,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (department_id, name)
);
CREATE INDEX IF NOT EXISTS department_service_department_idx ON DepartmentService (department_id);

